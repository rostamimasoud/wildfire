def table_premium():
    """The fire premium at each confidence, for both regions."""
    frames = []
    for name, region in REGIONS.items():
        data = solved(name)
        prem = data["premium"].copy()
        prem.insert(0, "region", region.label)
        prem["mean_over_credit"] = data["premium"].attrs["mean_over_credit"]
        prem["deterministic_cost"] = data["premium"].attrs["deterministic_cost"]
        prem["expectation_cost"] = data["premium"].attrs["expectation_cost"]
        frames.append(prem)
    df = pd.concat(frames, ignore_index=True)
    save_table(df, "premium")

    rows = []
    for name, region in REGIONS.items():
        data = solved(name)
        prem = data["premium"].set_index("confidence")
        ceil = data["ceiling"]
        entry = {"Region": region.label}
        for eta in HEADLINE:
            if eta in prem.index and bool(prem.loc[eta, "feasible"]):
                entry["$\\eta={:.2f}$".format(eta)] = (
                    100.0 * float(prem.loc[eta, "premium_vs_deterministic"])
                )
            else:
                entry["$\\eta={:.2f}$".format(eta)] = np.nan
        entry["Mean only"] = 100.0 * data["premium"].attrs["mean_over_credit"]
        entry["$\\eta_{\\max}$ exposed"] = ceil["confidence_max_exposed_only"]
        rows.append(entry)
    write_tex(
        pd.DataFrame(rows),
        "premium",
        "\\textbf{The fire premium.} Additional cost of achieving forcing "
        "neutrality at confidence $\\eta$, as a percentage of the cost under "
        "deterministic durability. ``Mean only'' is the part attributable to "
        "the expected loss of cooling, which any inventory owes regardless of "
        "the confidence sought; the remainder is the price of the guarantee. "
        "$\\eta_{\\max}$ is the confidence ceiling of the sub-portfolio that "
        "fire can reach.",
        "tab:premium",
        "%.3g",
    )
    return df


def table_composition():
    """Deployment and cooling share of every measure at each confidence."""
    frames = []
    for name, region in REGIONS.items():
        data = solved(name)
        fp = data["portfolio"]
        m = data["moments"]
        protected = np.array([s.hazard.is_inert for s in fp.stores])
        det = data["deterministic"]
        det_cool = det.alpha * m.deterministic
        rows = [
            {
                "region": region.label,
                "case": "deterministic",
                "confidence": np.nan,
                "cost": float(det.cost),
                "total_deployment_gt": float(det.alpha.sum()) / 1e12,
                "protected_share": float(det_cool[protected].sum() / det_cool.sum()),
                **{
                    "share_" + n: float(c / det_cool.sum())
                    for n, c in zip(fp.names, det_cool)
                },
            }
        ]
        for eta in CONFIDENCES:
            res = data["results"][eta]
            if not res.feasible:
                continue
            cool = res.alpha * m.mean
            rows.append(
                {
                    "region": region.label,
                    "case": "robust",
                    "confidence": float(eta),
                    "cost": float(res.cost),
                    "total_deployment_gt": float(res.alpha.sum()) / 1e12,
                    "protected_share": float(cool[protected].sum() / cool.sum()),
                    **{
                        "share_" + n: float(c / cool.sum())
                        for n, c in zip(fp.names, cool)
                    },
                }
            )
        frames.append(pd.DataFrame(rows))
    df = pd.concat(frames, ignore_index=True)
    save_table(df, "composition")

    name = "western_us"
    data = solved(name)
    fp = data["portfolio"]
    m = data["moments"]
    cols = {"Measure": [s.label for s in fp.stores]}
    det = data["deterministic"]
    dc = det.alpha * m.deterministic
    cols["Deterministic"] = dc / dc.sum()
    for eta in HEADLINE:
        res = data["results"][eta]
        if not res.feasible:
            continue
        c = res.alpha * m.mean
        cols["$\\eta={:.2f}$".format(eta)] = c / c.sum()
    write_tex(
        pd.DataFrame(cols),
        "composition",
        "\\textbf{Composition of the robust portfolio, western United "
        "States.} Share of delivered cooling supplied by each measure. The "
        "deterministic column credits every measure as though no fire "
        "occurred; the remaining columns hold neutrality with the stated "
        "confidence. Cooling migrates out of the measures fire can reach as "
        "the guarantee tightens.",
        "tab:composition",
        "%.3f",
    )
    return df


def table_variance():
    """How the variance of delivered cooling decomposes."""
    rows = []
    for name, region in REGIONS.items():
        data = solved(name)
        m = data["moments"]
        fp = data["portfolio"]
        for i, store in enumerate(fp.stores):
            if store.hazard.is_inert:
                continue
            tot = float(m.covariance[i, i])
            rows.append(
                {
                    "region": region.label,
                    "measure": store.label,
                    "variance_total": tot,
                    "variance_idiosyncratic": float(m.idiosyncratic[i, i]),
                    "variance_common": float(m.common[i, i]),
                    "common_share": float(m.common[i, i] / tot) if tot > 0 else np.nan,
                    "coefficient_of_variation": float(m.coefficient_of_variation[i]),
                }
            )
    df = pd.DataFrame(rows)
    save_table(df, "variance_decomposition")
    pretty = pd.DataFrame(
        {
            "Region": df["region"],
            "Measure": df["measure"],
            "$\\Sigma_{ii}$": df["variance_total"],
            "Diversifiable": 1.0 - df["common_share"],
            "Common": df["common_share"],
            "$\\sigma_i/\\mu_i$": df["coefficient_of_variation"],
        }
    )
    write_tex(
        pretty,
        "variance_decomposition",
        "\\textbf{Decomposition of the variance of delivered cooling.} "
        "$\\Sigma_{ii}$ is the total variance of the cooling measure $i$ "
        "delivers over the horizon, in $\\mathrm{K}^2\\,\\mathrm{yr}^2\\,"
        "\\mathrm{kg}^{-2}$. The diversifiable share arises from the timing "
        "and severity of fire at an individual site and falls as independent "
        "sites are added; the common share arises from the regional "
        "fire-weather year, is shared by every store in the region and does "
        "not fall. The last column is the coefficient of variation. Only "
        "measures fire can reach are listed; the fire-proof measures have "
        "zero variance by construction.",
        "tab:variance",
        float_format="%.3g",
    )
    return df


def table_sources():
    """The published aggregates the calibration rests on."""
    rows = []
    for key, entry in PUBLISHED.items():
        rows.append(
            {
                "quantity": key,
                "value": entry.get("value"),
                "units": entry.get("units", ""),
                "period": entry.get("period", ""),
                "source": entry.get("source", ""),
                "note": entry.get("note", ""),
            }
        )
    df = pd.DataFrame(rows)
    save_table(df, "sources")

    def provenance(row):
        text = tex_escape(row["source"])
        if row["period"]:
            text += ", " + tex_escape(row["period"])
        if row["note"]:
            text += ". " + tex_escape(row["note"])
        return text

    pretty = pd.DataFrame(
        {
            "Quantity": [
                tex_escape(q.replace("_", " ")).capitalize() for q in df["quantity"]
            ],
            "Value": [
                "{:g}".format(v) if pd.notna(v) else "--" for v in df["value"]
            ],
            "Units": [tex_escape(u) if u else "--" for u in df["units"]],
            "Source and note": [provenance(r) for _, r in df.iterrows()],
        }
    )
    write_tex(
        pretty,
        "sources",
        "\\textbf{Published aggregates the calibration rests on.} Every "
        "quantity that enters the fire model is listed with the value, the "
        "unit and the study it is taken from. Where a model parameter is not "
        "observed directly it is inverted from one of these aggregates, and "
        "the inversion is stated in Step~8 of the Methods rather than "
        "buried.",
        "tab:sources",
        column_format="l r l p{0.46\\textwidth}",
    )
    return df


