SI_DIR = os.path.join(TAB_DIR, "tex")
os.makedirs(SI_DIR, exist_ok=True)


def tex_escape(text):
    """Make a free-text cell safe for LaTeX, since bodies are written raw."""
    out = str(text)
    for char, repl in (
        ("\\", r"\textbackslash{}"),
        ("&", r"\&"),
        ("%", r"\%"),
        ("$", r"\$"),
        ("#", r"\#"),
        ("_", r"\_"),
        ("{", r"\{"),
        ("}", r"\}"),
        ("~", r"\textasciitilde{}"),
        ("^", r"\textasciicircum{}"),
    ):
        out = out.replace(char, repl)
    return out


def write_tex(
    df,
    name,
    caption,
    label,
    float_format="%.3g",
    index=False,
    column_format=None,
    longtable=False,
):
    """Write a booktabs table body for \\input into the manuscript."""
    path = os.path.join(SI_DIR, name + ".tex")
    if column_format is None:
        column_format = "l" + "r" * (df.shape[1] - (0 if index else 1))
    body = df.to_latex(
        index=index,
        escape=False,
        float_format=lambda v: format(v, float_format.lstrip("%")),
        column_format=column_format,
        longtable=longtable,
        caption=caption if longtable else None,
        label=label if longtable else None,
    )
    with open(path, "w") as fh:
        fh.write("% Generated by scripts/make_tables.py -- do not edit by hand.\n")
        if not longtable:
            fh.write("\\begin{table}[!htbp]\n\\centering\n\\footnotesize\n")
            fh.write("\\caption{{{}}}\n\\label{{{}}}\n".format(caption, label))
        fh.write(body)
        if not longtable:
            fh.write("\\end{table}\n")
    print("  tex    -> results/tables/tex/{}.tex".format(name))
    return path


